#requires -Version 7.0
[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent
$canonicalRoot = Join-Path $projectRoot '.agents/skills'
$adapterRoot = Join-Path $projectRoot '.claude/skills'
$skills = @(Get-ChildItem -LiteralPath $canonicalRoot -Directory | Sort-Object Name)
foreach ($skill in $skills) {
    $entry = Get-Content -LiteralPath (Join-Path $skill.FullName 'SKILL.md') -Raw
    $name = [regex]::Match($entry, '(?m)^name:\s*([^\r\n]+)').Groups[1].Value.Trim().Trim('"')
    $description = [regex]::Match($entry, '(?m)^description:\s*([^\r\n]+)').Groups[1].Value.Trim()
    if ($name -ne $skill.Name -or !$description) { throw "Invalid skill metadata: $($skill.Name)" }
    $text = @"
---
name: $name
description: $description
---

<!-- Generated by scripts/sync-claude-skills.ps1; edit the canonical skill. -->
Read [the canonical $name skill](../../../.agents/skills/$name/SKILL.md) and follow it.
Resolve its relative references/scripts against `.agents/skills/$name/` at the repository root.
Load only the references needed for this request. Shared AGENTS.md rules take precedence
for this project's Rojo ownership, collaboration and approval workflow.
Use tools actually available in Claude Code; never invent a connection or tool name.
"@
    $text = $text.Replace("`r`n", "`n") + "`n"
    $adapter = Join-Path $adapterRoot "$name/SKILL.md"
    if ($Check) {
        if (!(Test-Path -LiteralPath $adapter) -or
            (Get-Content -LiteralPath $adapter -Raw).Replace("`r`n", "`n") -ne $text) {
            throw "Claude adapter is missing/stale: $name. Run scripts/sync-claude-skills.ps1."
        }
    } else {
        New-Item -ItemType Directory -Path (Split-Path $adapter) -Force | Out-Null
        [IO.File]::WriteAllText($adapter, $text, [Text.UTF8Encoding]::new($false))
    }
}
$adapters = @(Get-ChildItem -LiteralPath $adapterRoot -Directory)
if (@($adapters | Where-Object Name -notin $skills.Name).Count) {
    throw 'Extra Claude adapter found. Review it before removing or retaining it.'
}
Write-Output "Claude skill adapters: $($skills.Count) $(if ($Check) { 'verified' } else { 'synchronized' })."
